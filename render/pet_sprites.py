# 心情 -> 眼睛字符。这一层是本项目加的：原作眼睛只做装饰性随机，我们把它
# 接到宠物真实状态上，让「看一眼屏幕」能读出「它现在饿不饿/高不高兴」。
EYES = {
    "happy": "·",   # ·  眯眼，满足
    "neutral": "•",  # •  平常
    "hungry": "×",   # ×  没精神
    "sad": "@",           # 委屈
    "alert": "◉",    # ◉  刚被摸过，精神
    "waiting": "?",  # ?  有个操作在等你批准（buddy-bridge 信号）
}


def render_frame(species: str, frame_index: int, eye: str) -> list[str]:
    frames = SPECIES.get(species, SPECIES["duck"])
    frame = frames[frame_index % len(frames)]
    return [line.replace("{E}", eye) for line in frame]
