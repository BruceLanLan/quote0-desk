DEFAULT_SPECIES = "duck"

# 前端下拉框的选项、API 的合法值校验都以这两个字典为准，漏一个就早点炸在
# 导入阶段，而不是等推送时渲染出一张空白卡。
assert set(SPECIES_LABELS) == set(SPECIES), "SPECIES_LABELS 和 SPECIES 的 key 对不上"


def is_valid_species(species: str) -> bool:
    """API 层校验用：前端传进来的造型名是不是真的存在。`render_frame()` 虽然
    有兜底，但"悄悄回退成鸭子"和"明确告诉用户这个值不合法"是两件事。"""
    return species in SPECIES


def render_frame(species: str, state: str, frame_index: int) -> list[str]:
    species_frames = SPECIES.get(species, SPECIES[DEFAULT_SPECIES])
    frames = species_frames.get(state) or species_frames["idle"]
    return list(frames[frame_index % len(frames)])
